def split_ref_prefix(token):
    """Split SHADOW:/ROOT: prefixes off a reference, as the engine does."""
    prefix = ""
    rest = token
    if rest.startswith("SHADOW:"):
        prefix = "SHADOW:"
        rest = rest[len("SHADOW:"):]
    if rest.startswith("ROOT:"):
        prefix += "ROOT:"
        rest = rest[len("ROOT:"):]
    return prefix, rest


def resolve_to_member(token, config_name, root, member_lower):
    """Resolve one reference token to the member it names, or None.

    Returns ``(prefix, original_member_name)``.  Built-in SHARED:/CORE:
    references are never rewritten, and values containing macros are left
    for --resolve to deal with.
    """
    token = token.strip()
    if not token or "${" in token:
        return None
    prefix, rest = split_ref_prefix(token)
    if rest.startswith(("SHARED:", "CORE:")):
        return None
    stripped = rest.replace("\\", "/").rstrip("/")
    if not stripped:
        return None
    if prefix.endswith("ROOT:"):
        bases = [root]
    else:
        curdir = config_name.rsplit("/", 1)[0] + "/" if "/" in config_name else ""
        bases = [curdir]
        parent = (curdir.rstrip("/").rsplit("/", 1)[0] + "/"
                  if "/" in curdir.rstrip("/") else "")
        if parent and parent != curdir:
            bases.append(parent)
        if root:
            bases.append(root)
    for base in bases:
        candidate = rt.normpath(base + stripped).lower()
        if candidate in member_lower:
            return prefix, member_lower[candidate]
    return None


def iter_refs(value, config_name, root, member_lower):
    """Yield every member referenced by one ini value."""
    if not value:
        return
    for part in value.split(","):
        got = resolve_to_member(part, config_name, root, member_lower)
        if got:
            yield got


