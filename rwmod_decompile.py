def main(argv=None):
    ap = argparse.ArgumentParser(
        description="Decompile a Rusted Warfare .rwmod into a readable "
                    "source tree (content-driven file names).")
    ap.add_argument("input", nargs="?", help="input .rwmod / .zip / .apk")
    ap.add_argument("-o", "--out-dir", default=None,
                    help="output folder (default: <input>_decompiled next "
                         "to the input file)")
    ap.add_argument("--config-ext", choices=("ini", "keep"), default="ini",
                    help="extension for config files: 'ini' renames every "
                         "config to .ini (readable; default), 'keep' keeps "
                         "the original extension (extensionless stays "
                         "extensionless)")
    ap.add_argument("--resolve", action="store_true",
                    help="write the fully expanded (copyFrom / ${...} "
                         "inlined) content instead of the normalized "
                         "original")
    ap.add_argument("--resolve-template", action="store_true",
                    help="also inline all-units.template into each unit and "
                         "drop the template files (implies --resolve)")
    ap.add_argument("--repair", action="store_true",
                    help="force the repair reader for zips with mangled "
                         "header fields (automatic when the normal reader "
                         "fails)")
    ap.add_argument("--list", action="store_true",
                    help="only print the old -> new name mapping")
    ap.add_argument("--no-progress", action="store_true",
                    help="disable the progress bar")
    ap.add_argument("--selftest", action="store_true",
                    help="run the built-in test and exit")
    args = ap.parse_args(argv)

    if args.selftest:
        return selftest()
    if not args.input:
        ap.print_help()
        return 2
    if not os.path.isfile(args.input):
        print("input not found: %s" % args.input, file=sys.stderr)
        return 2

    out_dir = args.out_dir
    if out_dir is None and not args.list:
        base = os.path.splitext(os.path.basename(args.input))[0]
        out_dir = os.path.join(
            os.path.dirname(os.path.abspath(args.input)),
            base + "_decompiled")

    try:
        stats = decompile(
            args.input,
            out_dir=out_dir,
            resolve=args.resolve or args.resolve_template,
            resolve_template=args.resolve_template,
            config_ext=args.config_ext,
            repair=args.repair,
            list_only=args.list,
            progress=rt.Progress(enabled=(False if args.no_progress else None)),
        )
    except zipfile.BadZipFile:
        print("error: %s is not a valid zip/rwmod" % args.input,
              file=sys.stderr)
        return 1
    except BrokenPipeError:
        # Piping --list into a command that stops reading early (e.g.
        # `--list | Select-Object -First 5`) must not raise at shutdown.
        sys.stdout = open(os.devnull, "w")
        return 0
    except (OSError, ValueError) as exc:
        print("error: %s" % exc, file=sys.stderr)
        return 1

    if args.list:
        return 0

    print("files written      : %d" % stats["files"])
    if stats["repaired"]:
        print("zip header repair  : yes")
    print("disguised names fix: %d" % stats["disguised"])
    print("configs decompiled : %d (units %d, bases %d, templates %d)"
          % (stats["configs"], stats["units"], stats["bases"],
             stats["templates"]))
    print("names from content : %d" % stats["named"])
    print("escaped fallbacks  : %d" % stats["escaped"])
    if stats["refs"]:
        print("references rewritten: %d" % stats["refs"])
    if args.resolve:
        print("unresolved macros  : %d file(s)" % stats["unresolved"])
    if stats["empty_dirs"]:
        print("empty folders      : %d ignored" % stats["empty_dirs"])
    print("output folder      : %s" % console_text(stats["out_dir"]))
    return 0


if __name__ == "__main__":
    print('版本信息：  '+VERSION)
    sys.exit(main())
