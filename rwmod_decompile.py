def selftest():
    tmp = tempfile.mkdtemp(prefix="rwdec_")
    try:
        zip_path = os.path.join(tmp, "t.rwmod")
        out_dir = os.path.join(tmp, "out")
        png = b"\x89PNG\r\n\x1a\n" + b"\x00" * 32
        base = "[core]\nprice:10\n"
        unit = ("[core]\n"
                "copyFrom: ROOT:mod/basecfg/\n"
                "displayText: TankUnit\n"
                "name: t1\n"
                "[graphics]\n"
                "image: ROOT:mod/pic1/\n")
        with zipfile.ZipFile(zip_path, "w") as zf:
            zf.writestr("mod/basecfg/", base)   # disguised config base
            zf.writestr("mod/pic1/", png)       # disguised image
            zf.writestr("mod/t1.ini", unit)
            zf.writestr("mod/raw.bin", png)     # unreferenced image

        stats = decompile(zip_path, out_dir,
                          progress=rt.Progress(enabled=False))

        expected = [
            os.path.join(out_dir, "units", "TankUnit.ini"),
            os.path.join(out_dir, "bases", "TankUnit_base.ini"),
            os.path.join(out_dir, "resources", "TankUnit_image.png"),
            os.path.join(out_dir, "resources", "raw.png"),
        ]
        for path in expected:
            if not os.path.isfile(path):
                print("SELFTEST FAILED (missing %s)" % path)
                return 1
        text = open(expected[0], "rb").read().decode("utf-8")
        if "ROOT:resources/TankUnit_image.png" not in text:
            print("SELFTEST FAILED (image ref): %r" % text)
            return 1
        if "ROOT:bases/TankUnit_base.ini" not in text:
            print("SELFTEST FAILED (copyFrom ref): %r" % text)
            return 1
        base_text = open(expected[1], "rb").read().decode("utf-8")
        if "price:10" not in base_text:
            print("SELFTEST FAILED (base content): %r" % base_text)
            return 1
        if stats["units"] != 1 or stats["bases"] != 1:
            print("SELFTEST FAILED (stats): %r" % stats)
            return 1

        # obfuscation cleanup + escaped fallback must stay unique
        if clean_text("\u200bco\u202ere") != "core":
            print("SELFTEST FAILED (clean_text section)")
            return 1
        dirty = rt.parse_ini("[\u200bco\u202ere]\rna\u2066me: Ta\u200bnk\r")
        cleaned = OrderedDict(
            (clean_text(sec), OrderedDict(
                (clean_text(k), clean_text(v)) for k, v in kv.items()))
            for sec, kv in dirty.items())
        if (list(cleaned) != ["core"]
                or list(cleaned["core"]) != ["name"]
                or cleaned["core"]["name"] != "Tank"):
            print("SELFTEST FAILED (parse obfuscated)")
            return 1
        if escaped_name("\u202e\U000e0d81") != "x202e_xe0d81_":
            print("SELFTEST FAILED (escaped_name)")
            return 1
        print("SELFTEST OK")
        return 0
    finally:
        import shutil
        shutil.rmtree(tmp, ignore_errors=True)


