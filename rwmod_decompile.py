# Format / directional / variation-selector / private-use characters that
# packers sprinkle over member names and ini content.  U+E0000..U+E0FFF also
# covers the supplementary variation selectors (U+E0100..U+E01EF).
INVISIBLE_RE = re.compile(
    "[\u00ad\u061c\u180e"
    "\u200b-\u200f"           # zero width + directional marks
    "\u202a-\u202e"           # embedding / override
    "\u2060-\u206f"           # word joiner, invisible operators, isolates
    "\ufeff\ufff9-\ufffb"
    "\ufe00-\ufe0f"           # variation selectors
    "\U000e0000-\U000e0fff]"  # tag block + supplementary PUA
)
CONTROL_RE = re.compile("[\u0000-\u001f\u007f-\u009f]")


def clean_text(text):
    """Drop invisible / private-use / control filler from a string."""
    return CONTROL_RE.sub("", INVISIBLE_RE.sub("", text))


def escaped_name(name):
    """Rewrite invisible characters as visible "xXXXX_" atoms.

    Unlike plain removal this keeps different obfuscated names distinct, so
    a file whose name carries no other information still gets a unique,
    eyeball-readable fallback name.
    """
    out = []
    for ch in name:
        if INVISIBLE_RE.match(ch) or CONTROL_RE.match(ch):
            out.append("x%04x_" % ord(ch))
        else:
            out.append(ch)
    return "".join(out)


_BAD_FS_CHARS = re.compile(r'[\\/:*?"<>|\u0000-\u001f]')
_RESERVED_NAMES = frozenset(
    ["CON", "PRN", "AUX", "NUL"]
    + ["COM%d" % i for i in range(1, 10)]
    + ["LPT%d" % i for i in range(1, 10)])


def sanitize_stem(text, fallback="file"):
    """Make a filesystem-safe file stem out of arbitrary config text."""
    stem = _BAD_FS_CHARS.sub("_", clean_text(text))
    stem = re.sub(r"\s+", "_", stem).strip("._ ")
    if len(stem) > 80:
        stem = stem[:80].rstrip("._ ")
    if not stem:
        stem = fallback
    if stem.split(".")[0].upper() in _RESERVED_NAMES:
        stem = "_" + stem
    return stem


