def console_text(text):
    """Make arbitrary Unicode safe for the current console encoding."""
    enc = getattr(sys.stdout, "encoding", None) or "utf-8"
    try:
        text.encode(enc)
        return text
    except (UnicodeEncodeError, LookupError):
        try:
            return text.encode(enc, "backslashreplace").decode(enc, "replace")
        except (UnicodeEncodeError, LookupError):
            return text.encode("ascii", "backslashreplace").decode("ascii")


def read_members(in_path, repair=False, progress=None):
    """Read all members, auto-switching to the repair reader if needed."""
    files = None
    repaired = False
    if not repair:
        try:
            zf = rt.open_zip(in_path)
            try:
                files, dirs = rt.collect(zf, progress)
            finally:
                zf.close()
        except Exception:
            files = None
    if files is None:
        files, dirs = rt.collect_repaired(in_path, progress)
        repaired = True
    return files, dirs, repaired


def decompile(in_path, out_dir, resolve=False, resolve_template=False,
              config_ext="ini", repair=False, list_only=False, progress=None):
    if resolve_template:
        resolve = True
    if progress is None:
        progress = rt.Progress()
    stats = {
        "files": 0,
        "disguised": 0,
        "repaired": False,
        "configs": 0,
        "units": 0,
        "bases": 0,
        "templates": 0,
        "named": 0,
        "escaped": 0,
        "refs": 0,
        "unresolved": 0,
        "empty_dirs": 0,
        "out_dir": out_dir,
    }

    files, dirs, stats["repaired"] = read_members(in_path, repair, progress)

    parsed, _ = rt.build_config_sections(
        files, False, resolve_template, progress)
    root = rt.detect_root([n for n, _d, _c in files])

    # build_config_sections() detects disguised configs only when they are
    # extensionless or reachable through copyFrom; protected packs may also
    # hide configs behind arbitrary extensions (e.g. .ogg).  A decoder plus
    # the "recognised section" requirement keeps binaries from matching.
    by_name = {n: d for n, d, _c in files}
    finder = rt.Resolver(parsed, root, resolve_template)
    finder.index = rt.FileIndex([n for n, _d, _c in files])
    work = []
    for name, data, _c in files:
        if name in parsed or rt.is_text_config(name):
            continue
        sections = rt._as_config(name, data, require_known=True)
        if sections is not None:
            parsed[name] = sections
            work.append(name)
    while work:
        name = work.pop()
        for target in rt._copyfrom_targets(parsed[name]):
            target_name = finder.resolve_target(target, name)
            if not target_name or target_name in parsed:
                continue
            sections = rt._as_config(
                target_name, by_name.get(target_name, b""))
            if sections is not None:
                parsed[target_name] = sections
                work.append(target_name)

    resolver = rt.Resolver(parsed, root, resolve_template)

    if progress:
        progress.phase("解析", len(parsed))
    resolved = OrderedDict()
    for name in parsed:
        resolved[name] = resolver.resolve(name)
        if progress:
            progress.step()

    plan, _displays, _owners, named, fallbacks = build_plan(
        files, parsed, resolved, resolver, root, config_ext)
    stats["named"] = named
    stats["escaped"] = fallbacks
    member_lower = {}
    for name in plan:
        member_lower.setdefault(name.lower(), name)

    if list_only:
        for name, data, _changed in files:
            print("%10d  %s  ->  %s"
                  % (len(data), console_text(name), console_text(plan[name])))
        progress.finish()
        return stats

    os.makedirs(out_dir, exist_ok=True)
    if progress:
        progress.phase("写出", len(files))
    for name, data, changed in files:
        if changed:
            stats["disguised"] += 1
        if name in parsed:
            if resolve_template and rt.is_template_entry(name):
                stats["templates"] += 1
                if progress:
                    progress.step()
                continue
            sections = resolved[name] if resolve else parsed[name]
            sections, hits = rewrite_sections(
                sections, name, plan, root, member_lower)
            stats["refs"] += hits
            data = rt.dump_ini(sections).encode("utf-8")
            stats["configs"] += 1
            if rt.is_template_entry(name):
                stats["templates"] += 1
            elif rt.is_modinfo(name):
                pass
            elif plan[name].startswith("units/"):
                stats["units"] += 1
            else:
                stats["bases"] += 1
            if resolve and b"${" in data:
                stats["unresolved"] += 1
        dest = rt.safe_member_path(out_dir, plan[name])
        parent = os.path.dirname(dest)
        if parent:
            os.makedirs(parent, exist_ok=True)
        with open(dest, "wb") as fh:
            fh.write(data)
        stats["files"] += 1
        if progress:
            progress.step()

    stats["empty_dirs"] = len(dirs)
    progress.finish()
    return stats


