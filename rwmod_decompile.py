def rewrite_value(value, file_name, dest_dir, plan, root, member_lower):
    """Rewrite every member reference inside one value; clean the rest.

    Returns ``(new_value, changed_count)``.
    """
    if not value:
        return clean_text(value), 0
    parts = value.split(",")
    out = []
    changed = 0
    for part in parts:
        token = part.strip()
        got = resolve_to_member(token, file_name, root, member_lower)
        if not got:
            out.append(clean_text(part))
            continue
        prefix, target = got
        new = plan[target]
        if prefix:
            replacement = prefix + new
        elif dest_dir:
            replacement = posixpath.relpath(new, dest_dir)
        else:
            replacement = new
        if replacement != token:
            changed += 1
        out.append(replacement)
    return ",".join(out), changed


def rewrite_sections(sections, file_name, plan, root, member_lower):
    """Clean one config and rewrite its references for the new layout."""
    dest_dir = posixpath.dirname(plan[file_name])
    out = OrderedDict()
    changed = 0
    for section, kv in sections.items():
        name = clean_text(section).strip() or section
        dest = out.setdefault(name, OrderedDict())
        for key, value in kv.items():
            key = clean_text(key).strip() or key
            value, hits = rewrite_value(
                value, file_name, dest_dir, plan, root, member_lower)
            dest[key] = value
            changed += hits
    return out, changed


