RESOURCE_EXTS = frozenset((
    ".png", ".jpg", ".jpeg", ".gif", ".bmp", ".webp", ".dds",
    ".ogg", ".wav", ".mp3", ".ttf", ".otf",
))


def magic_ext(data):
    """Return a canonical extension guessed from the file signature."""
    if data[:8] == b"\x89PNG\r\n\x1a\n":
        return ".png"
    if data[:4] == b"OggS":
        return ".ogg"
    if data[:4] == b"RIFF":
        if data[8:12] == b"WAVE":
            return ".wav"
        if data[8:12] == b"WEBP":
            return ".webp"
    if data[:3] == b"ID3":
        return ".mp3"
    if data[:2] in (b"\xff\xfb", b"\xff\xf3", b"\xff\xf2", b"\xff\xfa"):
        return ".mp3"
    if data[:6] in (b"GIF87a", b"GIF89a"):
        return ".gif"
    if data[:2] == b"\xff\xd8":
        return ".jpg"
    if data[:2] == b"BM":
        return ".bmp"
    if data[:4] in (b"\x00\x01\x00\x00", b"true", b"ttcf", b"OTTO"):
        return ".ttf"
    if data[:4] == b"DDS ":
        return ".dds"
    return ""


