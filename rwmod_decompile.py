_DISPLAY_KEYS = ("displayText", "displayText_zh", "displayName", "name")


def pick_display(sections, file_name=""):
    """Best readable label inside a config's effective content."""
    if rt.is_modinfo(file_name):
        sections_ = [sections.get("mod") or {}]
    else:
        sections_ = [sections.get("core") or {}]
    for section in sections_:
        for key in _DISPLAY_KEYS:
            value = section.get(key)
            if not value:
                continue
            value = clean_text(value).strip()
            if (not value or "${" in value
                    or value.lower() in ("null", "none", "nil", "-1")):
                continue
            return value
    return None


def basename_stem(name):
    base = name.replace("\\", "/").rsplit("/", 1)[-1]
    return os.path.splitext(base)[0]


def build_plan(files, parsed, resolved, resolver, root, config_ext):
    """Assign a final, readable path to every member.

    Returns ``(plan, displays, owners, named, fallbacks)``:
        plan       original name -> new relative path
        displays   config name   -> readable label
        owners     member name   -> (referrer display, key) for resources
        named      how many members got a content-driven name
        fallbacks  how many members fell back to an escaped name
    """
    names = [n for n, _d, _c in files]
    member_lower = {}
    for n in names:
        member_lower.setdefault(n.lower(), n)
    config_order = [n for n in names if n in parsed]

    # -- readable label for every config -----------------------------------
    displays = {}
    for n in config_order:
        displays[n] = pick_display(resolved[n], n)

    # configs without their own name borrow the first unit that copies them
    target_user = {}
    for n in config_order:
        for target in rt._copyfrom_targets(parsed.get(n, {})):
            found = resolver.resolve_target(target, n)
            if found and found not in target_user:
                target_user[found] = n
    for _ in range(8):                    # follow base-of-base chains
        changed = False
        for n in config_order:
            if displays.get(n):
                continue
            user = target_user.get(n)
            if user and displays.get(user):
                displays[n] = displays[user] + "_base"
                changed = True
        if not changed:
            break

    # -- which config/key references each resource -------------------------
    owners = {}
    for n in config_order:
        label = displays.get(n) or basename_stem(n)
        for _section, kv in resolved[n].items():
            for key, value in kv.items():
                if key.startswith("@"):
                    continue
                for _prefix, target in iter_refs(value, n, root, member_lower):
                    if target == n:
                        continue
                    if target not in owners:
                        owners[target] = (label, key)

    # -- final paths --------------------------------------------------------
    plan = {}
    taken = set()

    def unique(path):
        if path.lower() not in taken:
            taken.add(path.lower())
            return path
        head, ext = os.path.splitext(path)
        i = 2
        while True:
            candidate = "%s_%d%s" % (head, i, ext)
            if candidate.lower() not in taken:
                taken.add(candidate.lower())
                return candidate
            i += 1

    template_index = 0
    named = 0
    fallbacks = 0
    for n, data, _changed in files:
        if n not in parsed:
            ext = magic_ext(data)
            if not ext:
                ext = os.path.splitext(n.replace("\\", "/"))[1].lower()
            if n in owners:
                label, key = owners[n]
                stem = sanitize_stem(label + "_" + key)
                named += 1
            else:
                stem = sanitize_stem(escaped_name(basename_stem(n)))
                fallbacks += 1
            folder = "resources" if ext in RESOURCE_EXTS else "misc"
            plan[n] = unique("%s/%s%s" % (folder, stem, ext))
            continue
        if rt.is_modinfo(n):
            plan[n] = unique("mod-info.txt")
            continue
        if rt.is_template_entry(n):
            template_index += 1
            folder = ("templates" if template_index == 1
                      else "templates_%d" % template_index)
            plan[n] = folder + "/" + rt.basename(n)
            continue

        if displays.get(n):
            stem = sanitize_stem(displays[n])
            named += 1
        else:
            stem = sanitize_stem(escaped_name(basename_stem(n)))
            fallbacks += 1
        source_ext = os.path.splitext(n.replace("\\", "/"))[1].lower()
        if config_ext == "keep":
            ext = source_ext
        else:
            ext = ".ini"
        folder = "units" if source_ext == ".ini" else "bases"
        plan[n] = unique("%s/%s%s" % (folder, stem, ext))

    return plan, displays, owners, named, fallbacks


